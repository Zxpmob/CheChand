/* قیمت ماهانه‌ی واقعیِ N ماه پیش از امروز را برمی‌گرداند؛ اگر آن ماه در
   دیتای بالا نبود (چون خیلی جدید یا خیلی قدیمی است)، null برمی‌گرداند —
   به‌جای یک عدد نادرست. */
function goldMonthlyPriceMonthsAgo(monthsBack) {
  const now = new Date();
  let y = now.getFullYear();
  let m = now.getMonth() + 1 - monthsBack;
  while (m <= 0) { m += 12; y -= 1; }
  const row = GOLD_MONTHLY_USD.find((r) => r.y === y && r.m === m);
  return row ? row.p : null;
}
